"""
semafor_ha_momentum_20260910.py - Heiken Ashi Smoothed + Semafor + RSI momentum.

Location:  ~/src/trading/strategies/experimental/semafor_ha_momentum_20260910.py

Four layers, each answering a different question, and an entry needs all four
to agree. A smoothed Heiken Ashi ribbon says which way the macro tape leans; a
causally-confirmed swing pivot says the last leg has actually turned; RSI
leaving an extreme says momentum has re-engaged since that turn; and a close
crossing the fast EMA is the bar to act on. The pivot and the momentum gate
are the two that make this more than an EMA cross - they require the trigger
to arrive AFTER a structural low, not merely on a bar that happened to close
above a moving average.

================================================================================
STRATEGY SPECIFICATION & BACKTEST REQUEST  (filled from the 2026-09-10 request)
================================================================================
1. STRATEGY METADATA
   Strategy Name:       semafor_ha_momentum
   Strategy Archetype:  Trend-momentum breakout
   Primary Timeframe:   15m  (TIMEFRAME; the ladder is TIMEFRAMES)
   Target Assets:       the 19-contract matrix (SYMBOLS)

2. CORE CONCEPT & HYPOTHESIS
   A trend resumes from a structural pivot, not from an arbitrary bar. The
   inefficiency harvested is the gap between the pivot forming and the flow
   that follows it being recognised: participants who trade the level - stops
   under the swing low, breakout orders above it - act on confirmation, and
   confirmation is late by construction. It persists because the delay is
   structural rather than a view. The smoothed Heiken Ashi ribbon exists to
   refuse the setups that form against the macro lean, which is where a pivot
   is a pause in a larger move rather than the start of one.

3. INDICATORS & PARAMETER GRID
   Heiken Ashi Smoothed - EMA({ha_period}) over raw OHLC, Heiken Ashi built on
       the result, then EMA({ha_smooth}) over the HA candles. Bullish when
       close > HA_close AND the HA candle is green AND HA_close is rising.
   Semafor pivots      - a swing low/high over {swing_lookback} bars either
       side, CONFIRMED {swing_lookback} bars after it forms. See the causality
       note below; this is the whole reason the module is not a repainter.
   EMA({fast_ema})     - the micro trigger.
   RSI({rsi_period}), Wilder - the momentum gate at {rsi_oversold} /
       {rsi_overbought}.
   ATR(14), Wilder     - the protective stop only, never a signal level.

4. ENTRY & EXIT EXECUTION RULES
   Long:   Close crosses ABOVE EMA({fast_ema}), with a confirmed swing LOW
           within the last {momentum_window} bars, and RSI crossing above
           {rsi_oversold} at or after that pivot.
   Short:  Close crosses BELOW EMA({fast_ema}), with a confirmed swing HIGH
           within the last {momentum_window} bars, and RSI crossing below
           {rsi_overbought} at or after that pivot.
   Filter: the Heiken Ashi macro lean, when use_macro_trend is on.
   Exit:   the fast-EMA midline cross (use_midline_exit), the opposite
           trigger, and optionally RSI entering the opposite zone
           (use_rsi_zone_exit). A protective ATR stop sits underneath all of
           them.
   Session Rules:   none modelled - NOT SPECIFIED in the request.
   Execution Fill:  next-bar open, engine-applied slippage and commission.

5. BACKTEST EXECUTION CONTROLS
   Repository defaults: in-sample 2013-01-01..2022-12-31, holdout 2023-01-01
   onward and untouched during optimisation, Version B evaluated against A.

FOUR PLACES THE REQUEST LEFT A DECISION, MADE HERE AND FLAGGED
---------------------------------------------------------------
**"Version A / Version B" IN THE REQUEST IS NOT THIS REPOSITORY'S A/B, and
conflating them would have produced a module that cannot be promoted.** The
Dual-Version Mandate is fixed: Version A is the rule-based baseline and
Version B is *the same signals* with an ML filter over them, generated by
`backtest/promote.py`'s wrapper and adopted only if it beats A out of sample.
The request's "Version A: fixed stop / Version B: trailing stop with an RSI
target" describes two RISK CONFIGURATIONS of one rule set. Written as versions
they would collide with the mandate and Stage 3 would certify two things that
are not the pair it compares. They are therefore PARAMETERS - `sl_atr_mult`,
`trailing`, `use_midline_exit`, `use_rsi_zone_exit` - and the two requested
configurations are named in `RISK_VARIANTS` below. DEFAULT_PARAMS is the
request's Version A, because that is the baseline this package is.

**The Semafor is confirmed, not centred, and that is the difference between
this module and a repainter.** A Semafor marks a swing low at bar i when
`low[i]` is the lowest of the {swing_lookback} bars either side of it - which
is not known until {swing_lookback} MORE bars have printed. Read at bar i it
is lookahead; every backtest built on the centred form buys the exact bottom
and reports a Sharpe nothing can reproduce. Here the pivot is located at
`i - swing_lookback` and becomes True at bar i, so a signal on bar i reads
only bars <= i. The cost is real and is the point: the entry is late by
{swing_lookback} bars relative to the drawn arrow, exactly as it would be
live. `test_signals_do_not_change_when_future_bars_are_removed` holds it.

**"RSI crossing above 30 within a rolling window after a swing low" needs an
ordering, not just a window.** Both events inside the last {momentum_window}
bars is not the same claim as the RSI cross arriving AFTER the pivot - the
second is the hypothesis, the first also admits a cross that preceded the low
it is supposed to confirm. Implemented as the ordering: `bars_since_rsi_cross
<= bars_since_pivot`, with both inside the window.

**"RSI opposite zone take-profit" is a SIGNAL exit, not a bracket.** The
engine has no target ORDERS - `from_signals` is driven by boolean masks and
fills at the next bar's open - so a target expressed as "RSI reaches 70" can
only be an exit mask, detected on the bar that reaches it and filled one bar
later. `tp_atr_mult` stays None in both variants rather than being fitted to
approximate it, and `use_rsi_zone_exit` carries the rule where it belongs.

WHAT THE ENGINE CANNOT DO, STATED SO NO DRAWDOWN IS MISREAD
------------------------------------------------------------
There are no stop or target ORDERS anywhere in this repository. A stop is
detected on the bar that breaches it and filled at the NEXT bar's open, not at
the stop price. Every drawdown figure this module produces is therefore a
next-bar-open drawdown and is worse than a resting-order backtest would show.
The trailing stop in `RISK_VARIANTS["B_trailing"]` is a state machine inside
`_walk_loop`, and its high-water mark starts at the FILL bar, not the signal
bar.
"""

