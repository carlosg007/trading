def _ema(series: pd.Series, period: int) -> pd.Series:
    """
    A span-`period` exponential mean, NaN until `period` bars exist.

    `min_periods=period` rather than pandas' default of 1: without it the
    first bar's EMA is that bar's own close, which is not an average of
    anything, and a ribbon built from it leans wherever the first bar happened
    to sit.
    """
    return series.ewm(span=period, adjust=False, min_periods=period).mean()


def _wilder(series: pd.Series, period: int) -> pd.Series:
    """
    Wilder's smoothing - the average the ATR and the RSI are actually defined
    on.

    `alpha = 1/period` with `adjust=False` is Wilder's recursion exactly. A
    span-`period` EMA (`_ema` above) is a different, roughly twice as fast,
    average, and using it here would produce an "ATR(14)" and an "RSI(14)"
    that no other tool agrees with - so a reader checking a stop distance or
    an oversold reading against their own chart would see it somewhere else.
    """
    return series.ewm(alpha=1.0 / period, adjust=False,
                      min_periods=period).mean()


def _true_range(bars: pd.DataFrame) -> pd.Series:
    """
    True range per bar.

    `.shift(1)` looks one bar BACKWARD, which is the correct direction: the
    true range at bar i uses bar i-1's close and nothing later.
    """
    high, low, close = bars["high"], bars["low"], bars["close"]
    prev = close.shift(1)
    return pd.concat([(high - low).abs(),
                      (high - prev).abs(),
                      (low - prev).abs()], axis=1).max(axis=1)


def _atr(bars: pd.DataFrame, period: int = ATR_PERIOD) -> pd.Series:
    """
    True range, Wilder-smoothed. NaN until `period` bars exist.

    A ZERO ATR IS A MEASUREMENT, NOT A GAP, and it is left as the 0.0 it is.
    A window in which nothing moved - a halted contract, a dead overnight
    hour - has a true ATR of zero. `signal_fn` refuses to enter on such a bar
    rather than placing a bracket of zero width around the fill.
    """
    return _wilder(_true_range(bars), period)


def _as_series(value, index) -> pd.Series:
    """A scalar level as a Series on `index`; a Series is returned as-is."""
    if isinstance(value, pd.Series):
        return value
    return pd.Series(float(value), index=index)


def _cross_above(fast: pd.Series, level) -> pd.Series:
    """
    True on the bar `fast` crosses UP through `level` - a series or a scalar.

        fast[i] > level[i]  AND  fast[i-1] <= level[i-1]

    A STATE (`fast > level`) would be true for every bar of a run; this is the
    EVENT, true once. `<=` on the previous bar rather than `<` so a pair that
    was exactly equal and then separated counts as a cross - with two
    oscillators quantised by the same price series, exact equality is not the
    measure-zero event it is for two continuous curves.

    NaN-SAFE BY CONSTRUCTION: every comparison against NaN is False, so a
    warm-up bar is never a cross. `.shift(1)` looks one bar BACKWARD.
    """
    other = _as_series(level, fast.index)
    return (fast > other) & (fast.shift(1) <= other.shift(1))


def _cross_below(fast: pd.Series, level) -> pd.Series:
    """
    True on the bar `fast` crosses DOWN through `level`. The exact mirror of
    `_cross_above`, written out rather than expressed as its negation:
    `~_cross_above` is true on every bar that merely fails to be a cross up,
    which is almost all of them.
    """
    other = _as_series(level, fast.index)
    return (fast < other) & (fast.shift(1) >= other.shift(1))


def _rsi(close: pd.Series, period: int) -> pd.Series:
    """
    Wilder's RSI. NaN until `period` bars of change exist.

    Wilder-smoothed gains and losses, not a simple mean of them: the simple
    form is a different oscillator that crosses 30 on different bars, and this
    module's entire momentum gate is a threshold cross.

    A zero average loss gives RSI 100 rather than a division by zero - a
    window with no down bar is a real state, not a gap - and is produced here
    by letting the division yield `inf` and mapping it, rather than by a
    branch that would have to be repeated for the short side.
    """
    delta = close.diff()
    gain = delta.clip(lower=0.0)
    loss = (-delta).clip(lower=0.0)
    avg_gain = _wilder(gain, period)
    avg_loss = _wilder(loss, period)
    rs = avg_gain / avg_loss.replace(0.0, np.nan)
    rsi = 100.0 - (100.0 / (1.0 + rs))
    # An all-gain window: avg_loss is 0, rs is NaN by the replace above, and
    # the honest reading is 100 - fully overbought - not "unknown".
    return rsi.where(~((avg_loss == 0.0) & (avg_gain > 0.0)), 100.0)


def _heiken_ashi_smoothed(bars: pd.DataFrame, period: int, smooth: int
                          ) -> dict[str, pd.Series]:
    """
    The smoothed Heiken Ashi ribbon: EMA the raw OHLC, build Heiken Ashi on
    the result, then EMA the HA candles.

    THE HA OPEN IS A RECURRENCE, AND IT IS COMPUTED AS ONE.

        HA_open[i] = (HA_open[i-1] + HA_close[i-1]) / 2

    which is exactly an EWM with `alpha=HA_OPEN_ALPHA` over `HA_close` shifted
    one bar - `y[i] = a*x[i] + (1-a)*y[i-1]` with `x[i] = HA_close[i-1]` and
    `a = 0.5`. Written that way rather than as a Python loop because it is
    vectorised and identical, not as an approximation of it.

    The one difference from the textbook form is the SEED: the textbook sets
    `HA_open[0] = (open[0] + close[0]) / 2` and this seeds at the first valid
    `HA_close`. The two converge by a factor of 2 per bar, so by the end of
    the `period` warm-up they differ by about 2^-period - and every bar of
    that warm-up is masked out of the signals anyway. Recorded because a
    reader comparing this ribbon against a charting package bar by bar will
    see it, and should know it is the seed and not the rule.

    Nothing here reads a bar later than i.
    """
    o = _ema(bars["open"].astype("float64"), period)
    h = _ema(bars["high"].astype("float64"), period)
    l = _ema(bars["low"].astype("float64"), period)      # noqa: E741
    c = _ema(bars["close"].astype("float64"), period)

    ha_close = (o + h + l + c) / 4.0
    ha_open = ha_close.shift(1).ewm(alpha=HA_OPEN_ALPHA, adjust=False).mean()
    ha_high = pd.concat([h, ha_open, ha_close], axis=1).max(axis=1)
    ha_low = pd.concat([l, ha_open, ha_close], axis=1).min(axis=1)

    return {
        "ha_open": _ema(ha_open, smooth),
        "ha_high": _ema(ha_high, smooth),
        "ha_low": _ema(ha_low, smooth),
        "ha_close": _ema(ha_close, smooth),
    }


def _swing_points(bars: pd.DataFrame, lookback: int
                  ) -> tuple[pd.Series, pd.Series]:
    """
    Semafor pivots, CONFIRMED rather than centred. Returns
    `(swing_low_confirmed, swing_high_confirmed)`, both True on the bar the
    pivot becomes knowable.

    THIS IS THE FUNCTION THAT DECIDES WHETHER THIS MODULE REPAINTS. A Semafor
    marks a swing low at bar `p` when `low[p]` is the lowest of the `lookback`
    bars on EITHER side of it. The right-hand side has not printed at bar `p`,
    so the arrow appears `lookback` bars later and every bar in between can
    erase it. A backtest that reads the centred mask at bar `p` buys the exact
    bottom of every leg and reports a curve nothing can reproduce live.

    Here the window is `2*lookback + 1` bars ending at bar i, the pivot sits
    at its CENTRE - bar `i - lookback` - and the mask is True at bar i. So a
    signal on bar i reads bars `i - 2*lookback .. i` and nothing later, and
    the entry is late by `lookback` bars relative to the drawn arrow, exactly
    as it would be live.

    `.rolling(...).min()` over the trailing window plus a `.shift(-lookback)`
    would be the same arithmetic and would be WRONG: a negative shift reads
    forward. The window is built trailing and the pivot is indexed backward
    inside it, so no negative shift appears anywhere in this module.

    Ties go to a pivot. `<=` against the window minimum admits a double
    bottom, which is a real structure; requiring a strict minimum would drop
    the flat-based ones entirely.
    """
    window = 2 * int(lookback) + 1
    low = bars["low"].astype("float64")
    high = bars["high"].astype("float64")

    win_min = low.rolling(window, min_periods=window).min()
    win_max = high.rolling(window, min_periods=window).max()

    # The candidate pivot is the CENTRE of the trailing window: `lookback`
    # bars back from the bar doing the confirming. `.shift(lookback)` is a
    # positive shift and looks BACKWARD.
    pivot_low = low.shift(int(lookback))
    pivot_high = high.shift(int(lookback))

    return (pivot_low <= win_min).fillna(False), \
           (pivot_high >= win_max).fillna(False)


def _bars_since(mask: pd.Series) -> np.ndarray:
    """
    Bars elapsed since `mask` was last True, as a float array; `inf` before
    the first True.

    Vectorised through a running maximum of the positions where the mask
    fired, rather than a Python loop: `np.maximum.accumulate` over
    `where(mask, i, -1)` carries the most recent hit forward, which is the
    same answer a loop would give and is what makes the ordering test in
    `_layers` a comparison of two arrays instead of a second walk.

    `inf` rather than a large integer for "never": every comparison against it
    is False, so a window test needs no separate has-fired branch.
    """
    idx = np.arange(len(mask), dtype="float64")
    hit = np.where(mask.to_numpy(dtype=bool), idx, -np.inf)
    last = np.maximum.accumulate(hit)
    return idx - last


